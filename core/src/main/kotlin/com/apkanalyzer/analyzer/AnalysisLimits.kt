package com.apkanalyzer.analyzer

/**
 * Жёсткие ограничения анализа. Защищают телефон от огромных файлов, zip-bomb
 * и специально испорченных структур (бесконечные циклы, гигантские таблицы).
 *
 * Если какой-то лимит срабатывает, анализ не падает: соответствующий этап
 * помечается как неполный, а итог получает категорию «недостаточно данных».
 */
data class AnalysisLimits(
    /** Максимальный размер APK, который вообще принимаем к анализу. */
    val maxApkBytes: Long = 300L * 1024 * 1024,
    /** Максимальное число записей в центральном каталоге ZIP. */
    val maxZipEntries: Int = 30_000,
    /** Сколько максимум байт можно распаковать за весь анализ (суммарно). */
    val maxTotalInflatedBytes: Long = 768L * 1024 * 1024,
    /** Подозрительный коэффициент сжатия (признак zip-bomb), если запись достаточно велика. */
    val maxCompressionRatio: Int = 150,
    /** Записи меньше этого размера не проверяются на коэффициент сжатия. */
    val compressionRatioMinBytes: Long = 4L * 1024 * 1024,
    /** Максимальный размер AndroidManifest.xml после распаковки. */
    val maxManifestBytes: Int = 8 * 1024 * 1024,
    /** Максимальный размер одного DEX-файла, который читаем целиком. */
    val maxDexBytes: Int = 96 * 1024 * 1024,
    /** Сколько DEX-файлов (classes*.dex) максимум разбираем. */
    val maxDexFiles: Int = 64,
    /** Сколько строк из всех DEX максимум просматриваем. */
    val maxDexStrings: Int = 2_000_000,
    /** Максимальная длина одной строки DEX/ресурса, которую рассматриваем. */
    val maxStringBytes: Int = 4096,
    /** Максимальный размер текстового ассета, который просматриваем на URL/IP. */
    val maxTextAssetBytes: Int = 2 * 1024 * 1024,
    /** Сколько текстовых ассетов максимум просматриваем. */
    val maxTextAssets: Int = 300,
    /** Максимальный размер APK Signing Block. */
    val maxSigningBlockBytes: Int = 32 * 1024 * 1024,
    /** Ограничения на число найденных индикаторов каждого типа (чтобы отчёт не разрастался). */
    val maxIndicatorsPerType: Int = 300,
    /** Максимальная глубина вложенности элементов XML. */
    val maxXmlDepth: Int = 64,
    /** Максимальное количество XML-элементов в манифесте. */
    val maxXmlElements: Int = 50_000,
)
